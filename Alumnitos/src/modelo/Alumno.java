package modelo;

import java.io.Serializable;
import java.util.ArrayList;

/**
 *
 * @author paolaschicote
 */
public class Alumno implements Serializable {

    private String nombre;
    private String apellido;
    private int edad;
    private ArrayList<Double> calificaciones;

    public Alumno(String nombre, String apellido, int edad, ArrayList<Double> calificaciones) {
        this.nombre = nombre;
        this.apellido = apellido;
        this.edad = edad;
        this.calificaciones = calificaciones;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getApellido() {
        return apellido;
    }

    public void setApellido(String apellido) {
        this.apellido = apellido;
    }

    public int getEdad() {
        return edad;
    }

    public void setEdad(int edad) {
        this.edad = edad;
    }

    public ArrayList<Double> getCalificaciones() {
        return calificaciones;
    }

    public void setCalificaciones(ArrayList<Double> calificaciones) {
        this.calificaciones = calificaciones;
    }

}
